export const getPlantById = (id: string): PlantLibraryEntry | undefined =>
  PLANT_LIBRARY.find(p => p.id === id)

export const getPlantsByCategory = (category: string): PlantLibraryEntry[] =>
  PLANT_LIBRARY.filter(p => p.category === category)

export const searchPlants = (query: string): PlantLibraryEntry[] => {
  const q = query.toLowerCase()
  return PLANT_LIBRARY.filter(p =>
    p.nameFr.toLowerCase().includes(q) ||
    p.nameEn.toLowerCase().includes(q) ||
    p.scientificName.toLowerCase().includes(q) ||
    p.tags.some(t => t.toLowerCase().includes(q)) ||
    p.description.toLowerCase().includes(q),
  )
}
